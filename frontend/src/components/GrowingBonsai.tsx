import { useEffect, useState } from "react";
import { GROWTH_MS, GROWTH_STEP_MS, GROWTH_STEPS, canonicalSvg, growth, svgDataUrl, type Atmosphere, type Growth } from "../lib/growth";

interface Encoded { palette: string[]; art: string; shape: string; atmosphere: Atmosphere }
interface Sample { growth: Growth; image: string }

const HOLD_MS = 1000;

/** Grows canonical pixels from the trunk base; `image` (the canonical SVG) replaces the layers on the last step. */
export function GrowingPixelBonsai({ growth: { scene, tree }, image, alt }: { growth: Growth; image: string; alt: string }) {
  const timing = (step: number) => ({ animationDuration: `${GROWTH_STEP_MS}ms`, animationDelay: `${step * GROWTH_STEP_MS}ms` });
  return (
    <div className="growing-bonsai relative">
      <svg viewBox="0 0 64 64" shapeRendering="crispEdges" aria-hidden="true" className="pixelated aspect-square block w-full">
        {scene.map(([x, y, width, fill], run) =>
          <rect key={`scene-${run}`} x={x} y={y} width={width} height="1" fill={fill} />)}
        {tree.map(([x, y, width, fill, step], run) =>
          <rect key={`tree-${run}`} x={x} y={y} width={width} height="1" fill={fill} className="bonsai-pixels" style={timing(step)} />)}
      </svg>
      <img src={image} alt={alt} style={timing(GROWTH_STEPS - 1)}
        className="bonsai-final pixelated absolute inset-0 aspect-square w-full object-contain" />
    </div>
  );
}

function decode({ palette, art, shape, atmosphere }: Encoded): Sample {
  if (art.length !== 4096) throw new Error("Invalid bonsai samples");
  const colors = [...art].map((digit) => palette[parseInt(digit, 36)]);
  return { growth: growth(colors, [...shape].map(Number), atmosphere), image: svgDataUrl(canonicalSvg(colors)) };
}

function selectSamples(samples: Sample[], previous: Sample[] = []): Sample[] {
  const available = samples.filter((sample) => !previous.includes(sample));
  return Array.from({ length: 3 }, () => {
    const index = crypto.getRandomValues(new Uint32Array(1))[0] % available.length;
    return available.splice(index, 1)[0];
  });
}

export function GrowingBonsaiShowcase() {
  const [samples, setSamples] = useState<Sample[]>([]);
  const [selected, setSelected] = useState<Sample[]>([]);
  const [generation, setGeneration] = useState(0);
  const [error, setError] = useState<string>();
  const [retry, setRetry] = useState(0);

  useEffect(() => {
    const controller = new AbortController();
    fetch("/previews/growing.json", { signal: controller.signal })
      .then(async (response) => {
        if (!response.ok) throw new Error(`Bonsai samples could not load (HTTP ${response.status})`);
        const raw: Encoded[] = await response.json();
        if (raw.length < 6) throw new Error("Invalid bonsai samples");
        const data = raw.map(decode);
        if (!controller.signal.aborted) {
          setSamples(data);
          setSelected(selectSamples(data));
        }
      })
      .catch((reason: unknown) => {
        if (!controller.signal.aborted) setError(reason instanceof Error ? reason.message : String(reason));
      });
    return () => controller.abort();
  }, [retry]);

  useEffect(() => {
    if (!samples.length) return;
    const preference = window.matchMedia("(prefers-reduced-motion: reduce)");
    let timer: ReturnType<typeof setInterval> | undefined;
    const update = () => {
      if (timer !== undefined) clearInterval(timer);
      if (preference.matches) return;
      timer = setInterval(() => {
        setSelected((previous) => selectSamples(samples, previous));
        setGeneration((previous) => previous + 1);
      }, GROWTH_MS + HOLD_MS);
    };
    update();
    preference.addEventListener("change", update);
    return () => {
      if (timer !== undefined) clearInterval(timer);
      preference.removeEventListener("change", update);
    };
  }, [samples]);

  if (error) return <div role="alert">
    {error}
    <button className="btn-ghost" onClick={() => { setError(undefined); setRetry((previous) => previous + 1); }}>Retry</button>
  </div>;

  return (
    <div className="grid grid-cols-3 gap-3 md:gap-4">
      {selected.map((sample, index) => (
        <div key={index} className={`glass-strong p-2 ${index === 1 ? "translate-y-4 md:translate-y-8" : ""}`}>
          <div className="glass-inset p-2">
            <GrowingPixelBonsai key={generation} growth={sample.growth} image={sample.image}
              alt="Growing pixel-art bonsai generated by the NFT renderer" />
          </div>
        </div>
      ))}
    </div>
  );
}
